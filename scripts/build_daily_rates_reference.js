#!/usr/bin/env node
/**
 * R2c (ROUTE_BUILDER_BUDGET_PLAN.md, Phase 4): turns data/cost_reference/daily_rates_by_country.csv
 * (the source of truth) into js/data/dailyRatesReference.js, so the Route Builder can compute the
 * Backpacker / Standard / Comfort levels synchronously, without fetching a CSV at runtime.
 *
 * Re-run after every edit of the CSV: node scripts/build_daily_rates_reference.js
 */
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..');
const SRC = path.join(REPO_ROOT, 'data/cost_reference/daily_rates_by_country.csv');
const OUT = path.join(REPO_ROOT, 'js/data/dailyRatesReference.js');

function parseCsv(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/).filter(Boolean)) {
    const cells = []; let cur = '', q = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
      else if (ch === '"') q = true; else if (ch === ',') { cells.push(cur); cur = ''; } else cur += ch;
    }
    cells.push(cur); rows.push(cells);
  }
  const [head, ...body] = rows;
  return body.map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const byCode = {};
parseCsv(fs.readFileSync(SRC, 'utf8')).forEach(r => {
  const row = { variant: r.variant || '', backpacker: +r.backpacker_eur_per_day, standard: +r.standard_eur_per_day, comfort: +r.comfort_eur_per_day };
  if (![row.backpacker, row.standard, row.comfort].every(n => n > 0)) throw new Error(`${r.country_code} ${row.variant}: missing level`);
  (byCode[r.country_code] = byCode[r.country_code] || []).push(row);
});

const lines = Object.keys(byCode).sort().map(code =>
  `  ${code}: [${byCode[code].map(x => `{ variant: ${JSON.stringify(x.variant)}, backpacker: ${x.backpacker}, standard: ${x.standard}, comfort: ${x.comfort} }`).join(', ')}],`);

fs.writeFileSync(OUT, `/**
 * GENERATED by scripts/build_daily_rates_reference.js from data/cost_reference/daily_rates_by_country.csv —
 * do not edit by hand, edit the CSV and re-run the script.
 *
 * Ground cost (accommodation + food + local transport + activities) in EUR per person per day, at
 * three reference levels. A country can have variant rows (safari, Patagonia, big city, ...); an
 * empty variant is the base row. Used by rbRouteCosts() (routeBuilderCore.js).
 */
const RB_DAILY_RATES = {
${lines.join('\n')}
};
`);
console.log(`wrote ${path.relative(REPO_ROOT, OUT)}: ${Object.keys(byCode).length} countries`);
